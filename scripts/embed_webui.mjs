#!/usr/bin/env node
/**
 * embed_webui.mjs — pack the built front-end into a C header.
 *
 *   bun --cwd frontend run build   # produces frontend/dist/index.html (single file)
 *   node scripts/embed_webui.mjs   # writes build/cellui_web.h
 *
 * The whole SPA is one self-contained HTML file (vite-plugin-singlefile), so a
 * single string literal is enough — no asset folder, no runtime extraction.
 * The header defines CELLUI_HAVE_EMBEDDED_WEB so cellui.cpp can compile with or
 * without a built front-end.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join, resolve, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const dist = join(root, 'frontend', 'dist', 'index.html')
// resolve() handles both absolute and relative argv[2] (bun included)
const outDir = process.argv[2] ? resolve(root, process.argv[2]) : join(root, 'build')
const out = join(outDir, 'cellui_web.h')

if (!existsSync(dist)) {
  console.error(`[embed] ${relative(root, dist)} not found — run 'bun --cwd frontend install && bun --cwd frontend run build' first`)
  process.exit(1)
}

const html = readFileSync(dist, 'utf8')
if (!html.includes('<div id="app">')) {
  console.error('[embed] dist/index.html does not look like a built SPA')
  process.exit(1)
}

// C++11 raw string literal: R"cellui(...)cellui" — no escaping of quotes,
// backslashes or newlines. Guard against the (astronomically unlikely) case of
// the delimiter appearing in the payload.
const delimiter = html.includes(')cellui"') ? 'celluiweb' : 'cellui'
const header = `// Generated by scripts/embed_webui.mjs — do not edit.
// The complete front-end (single-file bundle) embedded in the binary.
#ifndef CELLUI_WEB_H
#define CELLUI_WEB_H
#define CELLUI_HAVE_EMBEDDED_WEB 1
static constexpr const char *cellui_web_html = R"${delimiter}(${html})${delimiter}";
#endif
`

mkdirSync(outDir, { recursive: true })
writeFileSync(out, header)
console.log(`[embed] ${relative(root, dist)} (${(html.length / 1024).toFixed(1)} KiB) -> ${relative(root, out)}`)
