#!/usr/bin/env node
/**
 * embed_webui.mjs — pack the built front-end into a C header.
 *
 *   bun --cwd frontend run build   # produces frontend/dist/index.html (single file)
 *   node scripts/embed_webui.mjs   # writes build/cellui_web.h
 *
 * The whole SPA is one self-contained HTML file (vite-plugin-singlefile), so a
 * single string literal is enough — no asset folder, no runtime extraction.
 *
 * MSVC caps any one string literal at ~16380 bytes (error C2026 "string too
 * big, trailing characters truncated") and the bundle is far larger than that,
 * so the payload is emitted as chunks and joined at runtime. A single huge
 * literal only ever worked on GCC/Clang, which is why this surfaced the first
 * time cellui was compiled with MSVC.
 *
 * The header defines CELLUI_HAVE_EMBEDDED_WEB so cellui.cpp can compile with or
 * without a built front-end.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join, resolve, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const dist = join(root, 'frontend', 'dist', 'index.html')
// resolve() handles both absolute and relative argv[2] (bun included)
const outDir = process.argv[2] ? resolve(root, process.argv[2]) : join(root, 'build')
const out = join(outDir, 'cellui_web.h')

// comfortably below MSVC's ~16380-byte literal cap
const CHUNK = 8192

if (!existsSync(dist)) {
  console.error(`[embed] ${relative(root, dist)} not found — run 'bun --cwd frontend install && bun --cwd frontend run build' first`)
  process.exit(1)
}

let html = readFileSync(dist, 'utf8')
if (!html.includes('<div id="app">')) {
  console.error('[embed] dist/index.html does not look like a built SPA')
  process.exit(1)
}

// WebUI serves the embedded SPA for "/" verbatim and never auto-injects its
// native bridge. The page must load /webui.js itself or window.cell_bootstrap
// (and every other bind) is undefined, so the GUI reports "kernel not ready".
// Inject the bridge load unless the page already references it.
if (!html.includes('/webui.js')) {
  const tag = "\n<script src=\"/webui.js\"></script>\n"
  const headClose = html.indexOf('</head>')
  const headOpen = html.indexOf('<head>')
  if (headClose !== -1) html = html.slice(0, headClose) + tag + html.slice(headClose)
  else if (headOpen !== -1) html = html.slice(0, headOpen + 6) + tag + html.slice(headOpen + 6)
  else html = tag + html
}

// Guard against the (astronomically unlikely) case of the delimiter appearing
// in the payload — including across every emitted chunk.
const delimiter = html.includes(')cellui"') ? 'celluiweb' : 'cellui'

// Split by characters, not bytes: a chunk ending mid-UTF-8 sequence would not
// decode back to the original document.
const chunks = []
for (let i = 0; i < html.length; i += CHUNK) {
  chunks.push(html.slice(i, i + CHUNK))
}

const parts = chunks.map((c) => `    R"${delimiter}(${c})${delimiter}"`).join(',\n')
const header = `// Generated by scripts/embed_webui.mjs — do not edit.
// The complete front-end (single-file bundle) embedded in the binary.
//
// Emitted as ${chunks.length} chunks: MSVC rejects a single literal above
// ~16380 bytes (C2026) and this bundle is much larger than that.
#ifndef CELLUI_WEB_H
#define CELLUI_WEB_H
#define CELLUI_HAVE_EMBEDDED_WEB 1
#include <cstddef>
#include <string>
static constexpr std::size_t cellui_web_chunks = ${chunks.length};
static constexpr const char *cellui_web_parts[${chunks.length}] = {
${parts}
};
inline std::string cellui_web_html() {
    std::string out;
    out.reserve(${html.length});
    for (std::size_t i = 0; i < cellui_web_chunks; ++i) out += cellui_web_parts[i];
    return out;
}
#endif
`

mkdirSync(outDir, { recursive: true })
writeFileSync(out, header)
console.log(
  `[embed] ${relative(root, dist)} (${(html.length / 1024).toFixed(1)} KiB in ${chunks.length} chunks) -> ${relative(root, out)}`,
)
